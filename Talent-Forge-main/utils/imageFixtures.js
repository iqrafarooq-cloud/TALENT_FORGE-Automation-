// Pad it to `mb` with COM segments. A COM segment's length field is 16 bits, so anything past
// ~64 KB needs several — hence the loop. They are inserted immediately AFTER the APP0/JFIF
// segment, because JFIF requires APP0 to follow SOI directly; decoders skip COM wherever it
// sits, so the image still decodes to the same 1x1 pixel at any file size.
function jpgOfSize(mb) {
  const app0Length = BASELINE_JPEG.readUInt16BE(4); // the APP0 segment's own length field
  const insertAt = 4 + app0Length;
  const head = BASELINE_JPEG.subarray(0, insertAt);
  const rest = BASELINE_JPEG.subarray(insertAt);

  let remaining = Math.max(0, Math.round(mb * 1024 * 1024) - BASELINE_JPEG.length);
  const segments = [];
  while (remaining > 4) {
    const n = Math.min(65531, remaining - 4);
    const len = Buffer.alloc(2);
    len.writeUInt16BE(n + 2);
    segments.push(Buffer.concat([Buffer.from([0xff, 0xfe]), len, Buffer.alloc(n, 0x20)]));
    remaining -= n + 4;
  }
  return Buffer.concat([head, ...segments, rest]);
}

// The formats the scenarios reject. These are deliberately REAL files of their claimed type —
// a rejection test that sends garbage proves the app rejects garbage, not that it rejects GIF.
const OTHER_FORMATS = {
  GIF: () => ({
    mimeType: 'image/gif',
    // GIF89a header + logical screen descriptor + trailer.
    buffer: Buffer.concat([
      Buffer.from('GIF89a', 'ascii'),
      Buffer.from([0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x3b]),
    ]),
  }),
  PDF: () => ({
    mimeType: 'application/pdf',
    buffer: Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF\n', 'ascii'),
  }),
  SVG: () => ({
    mimeType: 'image/svg+xml',
    buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>', 'ascii'),
  }),
  WEBP: () => ({
    mimeType: 'image/webp',
    // RIFF container with a WEBP fourcc — enough for any sniffer to call it a WebP.
    buffer: Buffer.concat([
      Buffer.from('RIFF', 'ascii'),
      Buffer.from([0x1a, 0x00, 0x00, 0x00]),
      Buffer.from('WEBPVP8 ', 'ascii'),
      Buffer.alloc(14, 0),
    ]),
  }),
  TXT: () => ({ mimeType: 'text/plain', buffer: Buffer.from('not an image at all', 'ascii') }),
};

// ==================== Real photographs ====================

const MB = 1024 * 1024;
const REAL_DIR = path.join(__dirname, '..', 'images to upload for testing');

// The checked-in photographs, keyed by the `size MB` a feature table asks for.
//
// `exactBytes` is set ONLY where the byte count is the point of the test, and it is asserted
// below. AC 3.1 states the maximum as "10 MB" and the form's hint says "max. 10MB", so the
// boundary scenario is meaningless unless it sends 10 × 1024 × 1024 bytes and not one byte
// more or less. A file that someone later "optimises" would quietly turn that scenario into a
// test of 9.4 MB and it would go green while the defect it exists to catch went unobserved.
//
// Everywhere else `mb` is the nominal figure the feature table uses and the real file is
// allowed to differ by up to SIZE_TOLERANCE_MB — those rows only need "comfortably inside the
// limit" or "comfortably over 5 MB", never an exact figure. The true byte count is always
// reported back to the report via `sizeBytes`, so a row never claims a size it did not send.
const SIZE_TOLERANCE_MB = 0.25;

// A size may list SEVERAL photographs. `variant` picks between them, which is what lets the
// replace-an-image scenario upload a genuinely different file rather than the same bytes twice —
// re-sending identical bytes cannot distinguish "the replacement was applied" from "the original
// is still there".
const REAL_FILES = {
  JPG: {
    10: [{ file: 'Exact10MB.jpg', exactBytes: 10 * MB }],
    11: [{ file: '11Mb size.jpg', exactBytes: 11 * MB }],
    8: [{ file: 'less than 10MBsize.jpg' }],
  },
  PNG: {
    // The PNG half of the exact-boundary scenario. It had NO registered fixture until
    // 2026-08-03, so `Profile Photo | PNG | 10` fell through to the GENERATED path and sent a
    // 1x1 image — the one thing the note at the top of this file says must never happen on a
    // form that crops every accepted upload. The scenario failed on that row and its report read
    // "the app rejects exactly 10 MB", which is not what the app does.
    // Built by scripts/make-exact-10mb-png.js: a real photograph padded with one tEXt chunk to
    // exactly 10,485,760 bytes. Re-run that script if the source photograph is ever replaced.
    10: [{ file: 'Exact10MB.png', exactBytes: 10 * MB }],
    6: [{ file: 'larger than 5MB.png' }],
    5: [
      { file: 'less than 5MB.png' },
      { file: 'Screenshot 2026-07-24 184947_ZeeResizer.png' },
    ],
  },
  // Not an image at all, and a better wrong-format subject than a synthesised one: it is a real
  // Office document, so a form that sniffs content rather than trusting the extension still
  // rejects it. Its size is irrelevant — it is refused on type — so it is exempt from the
  // tolerance check that guards the size-driven fixtures.
  DOCX: {
    1: [{
      file: 'docx file.docx',
      mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
      sizeIrrelevant: true,
    }],
  },
};

const MIME_BY_FORMAT = { JPG: 'image/jpeg', JPEG: 'image/jpeg', PNG: 'image/png' };

function realFile(fmt, sizeMb, variant = 0) {
  const list = (REAL_FILES[fmt === 'JPEG' ? 'JPG' : fmt] || {})[sizeMb];
  if (!list || !list.length) return null;
  const entry = list[variant % list.length];
  const full = path.join(REAL_DIR, entry.file);
  if (!fs.existsSync(full)) {
    throw new Error(
      `imageFixtures: "${entry.file}" is registered for ${fmt} ${sizeMb} MB but is missing from `
      + `"${REAL_DIR}". Restore it rather than falling back to a generated file — the generated `
      + `one is a 1x1 image and this form runs uploads through a crop modal.`
    );
  }
  const buffer = fs.readFileSync(full);

  // Fail loudly on drift. A silently-resized fixture changes what the scenario tests without
  // changing a line of the scenario, which is the hardest kind of false green to find.
  if (entry.exactBytes && buffer.length !== entry.exactBytes) {
    throw new Error(
      `imageFixtures: "${entry.file}" must be exactly ${entry.exactBytes} bytes (${sizeMb} MB) `
      + `because the scenario using it asserts that precise boundary, but it is ${buffer.length} `
      + `bytes. Restore the original file.`
    );
  }
  if (!entry.exactBytes && !entry.sizeIrrelevant && Math.abs(buffer.length / MB - sizeMb) > SIZE_TOLERANCE_MB) {
    throw new Error(
      `imageFixtures: "${entry.file}" is registered as ~${sizeMb} MB but is `
      + `${(buffer.length / MB).toFixed(2)} MB, outside the ${SIZE_TOLERANCE_MB} MB tolerance. `
      + `Re-key it in REAL_FILES so the feature tables state the size they actually send.`
    );
  }

  return {
    name: entry.file,
    mimeType: entry.mimeType || MIME_BY_FORMAT[fmt] || 'application/octet-stream',
    buffer,
    source: 'real',
  };
}

// Build a Playwright setInputFiles payload.
//
// A real photograph is used whenever one is registered at this format and size; otherwise the
// bytes are generated. `sizeMb` is honoured for JPG/PNG only — the wrong-format cases are
// rejected on type, so padding them to 11 MB would confuse which rule fired and make a red row
// ambiguous.
function imageFile(format, sizeMb = 1, nameHint = 'upload', variant = 0) {
  const fmt = String(format).trim().toUpperCase();

  const real = realFile(fmt, sizeMb, variant);
  if (real) return real;

  const stamp = `${nameHint}-${fmt}-${sizeMb}mb`;
  if (fmt === 'PNG') return { name: `${stamp}.png`, mimeType: 'image/png', buffer: pngOfSize(sizeMb), source: 'generated' };
  if (fmt === 'JPG' || fmt === 'JPEG') return { name: `${stamp}.jpg`, mimeType: 'image/jpeg', buffer: jpgOfSize(sizeMb), source: 'generated' };
  const other = OTHER_FORMATS[fmt];
  if (!other) throw new Error(`imageFixtures: unsupported format "${format}"`);
  const { mimeType, buffer } = other();
  return { name: `${stamp}.${fmt.toLowerCase()}`, mimeType, buffer, source: 'generated' };
}

module.exports = { imageFile, pngOfSize, jpgOfSize, REAL_FILES, REAL_DIR };
