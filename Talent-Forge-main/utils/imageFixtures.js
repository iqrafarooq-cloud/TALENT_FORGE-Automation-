const zlib = require('zlib');
const fs = require('fs');
const path = require('path');

// imageFixtures — the bytes every upload scenario sends.
//
// TWO SOURCES, IN THIS ORDER.
//
// 1. REAL PHOTOGRAPHS, checked in under `images to upload for testing/`. These are preferred
//    whenever one exists at the requested format and size, and they are the only honest way to
//    test THIS form: uploading a cover opens a CROP MODAL, and a cropper handed a 1x1 image
//    behaves nothing like one handed a photograph. See the warning on BASELINE_JPEG below —
//    an undecodable fixture already broke this suite once, silently, by leaving the crop modal
//    open to swallow every later click while the upload still reported "accepted".
//    `Exact10MB.jpg` is exactly 10,485,760 bytes, which is the boundary AC 3.1 calls the
//    maximum and the app wrongly rejects; `11Mb size.jpg` is exactly 11 MB. Those two are
//    measured artefacts, not approximations, and that is precisely why they are files rather
//    than something a helper rounds to.
//
// 2. GENERATED BYTES, built in memory, for the combinations no real file covers — a 25 MB PNG
//    (committing one is 25 MB of binary for a single rejection row) and the GIF / PDF / SVG /
//    WEBP wrong-format cases, which only need to be valid files of their claimed type.
//
// WHY NOT RENAMED TEXT, for either source. A .jpg full of ASCII is rejected by anything that
// sniffs magic bytes, so a suite built on those would pass its rejection scenarios for the
// wrong reason and could never write an ACCEPTANCE scenario at all. Everything below is a
// genuinely valid file: for the generated ones the size comes from an ancillary chunk (PNG
// tEXt) or a comment segment (JPEG COM), both of which decoders skip, so a 25 MB PNG still
// decodes to the same 1x1 image a 2 MB one does.

function crc32(buf) {
  let c = ~0;
  for (let i = 0; i < buf.length; i += 1) {
    c ^= buf[i];
    for (let k = 0; k < 8; k += 1) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}

function pngChunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const typed = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typed));
  return Buffer.concat([len, typed, crc]);
}

// A valid 1x1 RGB PNG padded to `mb` megabytes (MB = 1024*1024 — the same definition the
// scenarios use when they say "exactly 10 MB").
function pngOfSize(mb) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(1, 0);
  ihdr.writeUInt32BE(1, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // colour type: truecolour
  const head = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', zlib.deflateSync(Buffer.from([0, 255, 0, 0]))),
  ]);
  const end = pngChunk('IEND', Buffer.alloc(0));
  const target = Math.round(mb * 1024 * 1024);
  const padLen = Math.max(0, target - head.length - end.length - 12);
  const pad = pngChunk('tEXt', Buffer.concat([Buffer.from('Comment\0', 'ascii'), Buffer.alloc(padLen, 0x41)]));
  return Buffer.concat([head, pad, end]);
}

